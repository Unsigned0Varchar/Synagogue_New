import { readFile, writeFile } from "node:fs/promises";
import path from "node:path";
import nodemailer from "nodemailer";

async function main() {
  const envLocalPath = path.join(process.cwd(), ".env.local");
  const envExamplePath = path.join(process.cwd(), ".env.example");

  console.log("Creating/updating .env.local with Ethereal SMTP test credentials...");

  try {
    // Generate test SMTP account
    const testAccount = await nodemailer.createTestAccount();
    console.log("Generated Ethereal SMTP Test Account successfully:");
    console.log(`- SMTP User: ${testAccount.user}`);
    console.log(`- Ethereal Login Page: https://ethereal.email`);

    let envContent = "";
    try {
      envContent = await readFile(envLocalPath, "utf8");
      console.log("Found existing .env.local. Appending/replacing SMTP credentials...");
    } catch (error) {
      if (error.code === "ENOENT") {
        try {
          envContent = await readFile(envExamplePath, "utf8");
          console.log("Created .env.local from .env.example template...");
        } catch (_) {
          envContent = "";
        }
      } else {
        throw error;
      }
    }

    // Parse existing lines and merge SMTP keys
    const lines = envContent.split(/\r?\n/);
    const envMap = new Map();

    for (const line of lines) {
      const trimmed = line.trim();
      if (!trimmed || trimmed.startsWith("#")) {
        continue;
      }
      const index = trimmed.indexOf("=");
      if (index !== -1) {
        const key = trimmed.slice(0, index).trim();
        const val = trimmed.slice(index + 1).trim();
        envMap.set(key, val);
      }
    }

    // Set SMTP credentials
    envMap.set("SMTP_HOST", testAccount.smtp.host);
    envMap.set("SMTP_PORT", String(testAccount.smtp.port));
    envMap.set("SMTP_SECURE", String(testAccount.smtp.secure));
    envMap.set("SMTP_USER", testAccount.user);
    envMap.set("SMTP_PASS", testAccount.pass);
    if (!envMap.get("SMTP_FROM")) {
      envMap.set("SMTP_FROM", `SYNAGOGUE Tickets <${testAccount.user}>`);
    }

    // If Razorpay or Twilio keys are not set, ensure they exist in map
    const defaultKeys = [
      "RAZORPAY_KEY_ID",
      "RAZORPAY_KEY_SECRET",
      "TWILIO_ACCOUNT_SID",
      "TWILIO_AUTH_TOKEN",
      "TWILIO_FROM_NUMBER"
    ];
    for (const key of defaultKeys) {
      if (!envMap.has(key)) {
        envMap.set(key, "");
      }
    }

    // Reconstruct env content
    const outputLines = [];
    outputLines.push("# SYNAGOGUE Local Dev Environment Config");
    outputLines.push("");
    
    outputLines.push("# Razorpay (Leave blank to use Demo checkout mode)");
    outputLines.push(`RAZORPAY_KEY_ID=${envMap.get("RAZORPAY_KEY_ID") || ""}`);
    outputLines.push(`RAZORPAY_KEY_SECRET=${envMap.get("RAZORPAY_KEY_SECRET") || ""}`);
    outputLines.push("");

    outputLines.push("# SMTP (Auto-generated by create-test-env.js)");
    outputLines.push(`SMTP_HOST=${envMap.get("SMTP_HOST")}`);
    outputLines.push(`SMTP_PORT=${envMap.get("SMTP_PORT")}`);
    outputLines.push(`SMTP_SECURE=${envMap.get("SMTP_SECURE")}`);
    outputLines.push(`SMTP_USER=${envMap.get("SMTP_USER")}`);
    outputLines.push(`SMTP_PASS=${envMap.get("SMTP_PASS")}`);
    outputLines.push(`SMTP_FROM=${envMap.get("SMTP_FROM")}`);
    outputLines.push("");

    outputLines.push("# Twilio SMS (Leave blank to skip SMS notifications)");
    outputLines.push(`TWILIO_ACCOUNT_SID=${envMap.get("TWILIO_ACCOUNT_SID") || ""}`);
    outputLines.push(`TWILIO_AUTH_TOKEN=${envMap.get("TWILIO_AUTH_TOKEN") || ""}`);
    outputLines.push(`TWILIO_FROM_NUMBER=${envMap.get("TWILIO_FROM_NUMBER") || ""}`);
    outputLines.push("");

    await writeFile(envLocalPath, outputLines.join("\n"), "utf8");
    console.log("Success! Updated .env.local file with active test email credentials.");
  } catch (error) {
    console.error("Failed to generate test environment:", error);
    process.exit(1);
  }
}

main();
